import { todayISO } from '../format';
import type { Cell, ColumnKind, TemplateOutput } from './templates';

export type FileFormat = 'csv' | 'json';

export interface ExportFile {
  name: string;
  mime: string;
  content: string;
}

function rawCell(value: Cell, kind: ColumnKind): string {
  if (value === null) return '';
  if (kind === 'currency') return Number(value).toFixed(2);
  if (kind === 'percent') return Number(value).toFixed(1);
  return String(value);
}

function escapeCsv(value: string, isText = true): string {
  // Neutralize spreadsheet formula injection in user-provided text, then quote if needed.
  // Numeric columns are generated by us, so negative numbers stay numeric.
  const safe = isText && /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;
  return /[",\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
}

export function toCsv(output: Pick<TemplateOutput, 'columns' | 'rows'>): string {
  const header = output.columns.map((c) => escapeCsv(c.label));
  const rows = output.rows.map((row) =>
    row.map((cell, i) => {
      const { kind } = output.columns[i];
      return escapeCsv(rawCell(cell, kind), kind === 'text' || kind === 'date');
    }),
  );
  return [header, ...rows].map((r) => r.join(',')).join('\r\n');
}

export function toJson(output: TemplateOutput, generatedAt: Date): string {
  return JSON.stringify(
    {
      app: 'Spendwise',
      template: output.templateId,
      title: output.title,
      period: output.periodLabel,
      generatedAt: generatedAt.toISOString(),
      highlights: output.highlights,
      rows: output.rows.map((row) => Object.fromEntries(output.columns.map((c, i) => [c.key, row[i]]))),
    },
    null,
    2,
  );
}

function slug(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

export function buildFile(output: TemplateOutput, format: FileFormat, generatedAt: Date): ExportFile {
  const name = `spendwise-${output.templateId}-${slug(output.periodLabel)}-${todayISO()}.${format}`;
  return format === 'csv'
    ? // BOM so Excel opens UTF-8 (emoji, accents) correctly.
      { name, mime: 'text/csv;charset=utf-8', content: '﻿' + toCsv(output) }
    : { name, mime: 'application/json', content: toJson(output, generatedAt) };
}

export function byteSize(content: string): number {
  return new Blob([content]).size;
}

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
}

export function downloadFile(file: ExportFile): void {
  const url = URL.createObjectURL(new Blob([file.content], { type: file.mime }));
  const link = document.createElement('a');
  link.href = url;
  link.download = file.name;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 0);
}
